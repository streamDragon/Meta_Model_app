import type { ResponseQuality } from './conversationSkills';

/** Authored possibilities in fictional dialogues, not predictions of real reactions. */
export interface RepairResponse {
  id: string;
  text: string;
  quality: ResponseQuality;
  feedback: string;
  reply: string;
}

export interface RepairMoment {
  prompt: string;
  choices: readonly [RepairResponse, RepairResponse, RepairResponse];
}

const repair = (id: string, text: string, quality: ResponseQuality, feedback: string, reply: string): RepairResponse =>
  ({ id, text, quality, feedback, reply });

